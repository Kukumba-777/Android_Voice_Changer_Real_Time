package dev.avcrt.core.ui

import androidx.compose.ui.unit.dp

/**
 * Design system spacing scale. Use these instead of literal dp values so that
 * a future density change (or accessibility tuning) is a one-file edit.
 */
object AvcrtSpacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val xxxl = 48.dp
}
